async def export_demo(
    session: AsyncSession, blob: BlobStore, analysis_id: uuid.UUID, out_dir: Path
) -> None:
    analysis = await session.get(Analysis, analysis_id)
    if analysis is None or analysis.status != AnalysisStatus.SUCCEEDED:
        raise SystemExit("Analysis not found or not succeeded")
    region_slug = None
    if analysis.region_id:
        region = await session.get(Region, analysis.region_id)
        region_slug = region.slug if region else None
    scenes = (
        (await session.execute(select(Scene).where(Scene.analysis_id == analysis_id)))
        .scalars()
        .all()
    )
    observations = (
        (await session.execute(select(Observation).where(Observation.analysis_id == analysis_id)))
        .scalars()
        .all()
    )
    artifacts = (
        (await session.execute(select(Artifact).where(Artifact.analysis_id == analysis_id)))
        .scalars()
        .all()
    )

    if out_dir.exists():
        shutil.rmtree(out_dir)
    blob_dir = out_dir / "blobs"
    blob_dir.mkdir(parents=True)

    bundled: list[dict[str, Any]] = []
    for artifact in artifacts:
        if artifact.artifact_type not in BUNDLED_ARTIFACT_TYPES:
            continue
        data = await anyio.to_thread.run_sync(blob.download_bytes, artifact.blob_path)
        local_name = artifact.blob_path.replace("/", "__")
        (blob_dir / local_name).write_bytes(data)
        record = _record(artifact, ARTIFACT_FIELDS)
        record["file"] = f"blobs/{local_name}"
        bundled.append(record)

    manifest = {
        "format_version": "1.0",
        "attribution": (
            "Derived previews and statistics from Copernicus Sentinel-2 data "
            "(ESA), accessed via Microsoft Planetary Computer. Sentinel data is "
            "provided under the Legal Notice on the use of Copernicus Sentinel "
            "Data and Service Information."
        ),
        "region_slug": region_slug,
        "analysis": _record(analysis, ANALYSIS_FIELDS),
        "scenes": [_record(s, SCENE_FIELDS) for s in scenes],
        "observations": [_record(o, OBSERVATION_FIELDS) for o in observations],
        "artifacts": bundled,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"exported demo bundle to {out_dir} ({len(bundled)} artifacts)")


async def import_demo(session: AsyncSession, blob: BlobStore, bundle_dir: Path) -> uuid.UUID:
    manifest = json.loads((bundle_dir / "manifest.json").read_text())
    a = manifest["analysis"]
    analysis_id = uuid.UUID(a["id"])
    existing = await session.get(Analysis, analysis_id)
    if existing is not None:
        print(f"demo analysis {analysis_id} already imported")
        return analysis_id

    region_id = None
    if manifest.get("region_slug"):
        region = (
            await session.execute(select(Region).where(Region.slug == manifest["region_slug"]))
        ).scalar_one_or_none()
        region_id = region.id if region else None

    def parse_dt(value: str | None) -> datetime | None:
        return datetime.fromisoformat(value) if value else None

    session.add(
        Analysis(
            id=analysis_id,
            region_id=region_id,
            geometry=from_shape(bbox_polygon(tuple(a["bbox"])), srid=4326)
            if region_id is None
            else None,
            bbox=a["bbox"],
            area_km2=a["area_km2"],
            start_date=date.fromisoformat(a["start_date"]),
            end_date=date.fromisoformat(a["end_date"]),
            collection=a["collection"],
            max_cloud_cover_pct=a["max_cloud_cover_pct"],
            scene_limit=a["scene_limit"],
            operation=a["operation"],
            processing_config=a["processing_config"],
            grid=a.get("grid"),
            processing_version=a["processing_version"],
            git_commit_sha=a.get("git_commit_sha"),
            status=AnalysisStatus(a["status"]),
            status_message="Imported precomputed demonstration analysis",
            submitted_at=parse_dt(a["submitted_at"]) or datetime.now(UTC),
            started_at=parse_dt(a.get("started_at")),
            completed_at=parse_dt(a.get("completed_at")),
            retry_count=a.get("retry_count", 0),
            output_prefix=a.get("output_prefix"),
            summary=a.get("summary"),
            is_demo=True,
        )
    )
    for s in manifest["scenes"]:
        session.add(
            Scene(
                id=uuid.UUID(s["id"]),
                analysis_id=analysis_id,
                stac_collection=s["stac_collection"],
                stac_item_id=s["stac_item_id"],
                acquisition_key=s.get("acquisition_key"),
                contributing_item_ids=s.get("contributing_item_ids"),
                tile_ids=s.get("tile_ids"),
                granule_count=s.get("granule_count") or 1,
                aoi_coverage_pct=s.get("aoi_coverage_pct"),
                valid_pixel_pct=s.get("valid_pixel_pct"),
                observed_at=datetime.fromisoformat(s["observed_at"]),
                bbox=s.get("bbox"),
                cloud_cover_pct=s.get("cloud_cover_pct"),
                source_provider=s["source_provider"],
                platform=s.get("platform"),
                instruments=s.get("instruments"),
                assets=s["assets"],
                selection_status=SceneSelectionStatus(s["selection_status"]),
                exclusion_reason=s.get("exclusion_reason"),
                quality=s.get("quality"),
            )
        )
    for o in manifest["observations"]:
        values = {k: o[k] for k in OBSERVATION_FIELDS}
        values["id"] = uuid.UUID(values["id"])
        values["analysis_id"] = uuid.UUID(values["analysis_id"])
        values["scene_id"] = uuid.UUID(values["scene_id"])
        session.add(Observation(**values))
    for art in manifest["artifacts"]:
        data = (bundle_dir / art["file"]).read_bytes()
        local_tmp = bundle_dir / "._upload.tmp"
        local_tmp.write_bytes(data)
        await anyio.to_thread.run_sync(
            blob.upload_file, local_tmp, art["blob_path"], art["content_type"]
        )
        local_tmp.unlink()
        session.add(
            Artifact(
                id=uuid.UUID(art["id"]),
                analysis_id=analysis_id,
                scene_id=uuid.UUID(art["scene_id"]) if art.get("scene_id") else None,
                artifact_type=ArtifactType(art["artifact_type"]),
                container=art["container"],
                blob_path=art["blob_path"],
                content_type=art["content_type"],
                size_bytes=art["size_bytes"],
                sha256=art["sha256"],
                crs=art.get("crs"),
                bbox=art.get("bbox"),
                provenance=art.get("provenance"),
            )
        )
    await session.commit()
    print(f"imported demo analysis {analysis_id}")
    return analysis_id


async def _run(args: argparse.Namespace) -> None:
    settings = get_settings()
    configure_logging(settings.log_level, service="oeop-admin")
    engine = create_engine(settings)
    factory: async_sessionmaker[AsyncSession] = create_session_factory(engine)
    try:
        if args.command == "seed-regions":
            async with factory() as session:
                await seed_regions(session)
        elif args.command == "seed-demo":
            queue = AnalysisQueue(settings)
            queue.ensure_queues()
            BlobStore(settings).ensure_container()
            async with factory() as session:
                await seed_demo(
                    session,
                    queue,
                    settings,
                    slug=args.slug,
                    start=date.fromisoformat(args.start),
                    end=date.fromisoformat(args.end),
                    cloud=args.cloud,
                    scenes=args.scenes,
                    if_missing=args.if_missing,
                )
        elif args.command == "requeue":
            queue = AnalysisQueue(settings)
            async with factory() as session:
                await requeue(session, queue, uuid.UUID(args.analysis_id))
        elif args.command == "delete-analysis":
            blob = BlobStore(settings)
            async with factory() as session:
                await delete_analyses(
                    session,
                    blob,
                    analysis_ids=[uuid.UUID(a) for a in (args.analysis_id or [])],
                    legacy=args.legacy,
                    dry_run=args.dry_run,
                    force=args.force,
                )
        elif args.command == "queue-depth":
            queue = AnalysisQueue(settings)
            print(queue.approximate_depth())
        elif args.command == "export-demo":
            blob = BlobStore(settings)
            async with factory() as session:
                await export_demo(session, blob, uuid.UUID(args.analysis_id), Path(args.out))
        elif args.command == "import-demo":
            blob = BlobStore(settings)
            blob.ensure_container()
            async with factory() as session:
                await import_demo(session, blob, Path(args.bundle))
        else:  # pragma: no cover - argparse enforces choices
            raise SystemExit(f"Unknown command {args.command}")
    finally:
        await engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser(prog="oeop-admin", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("seed-regions", help="Upsert predefined regions")

    demo = sub.add_parser("seed-demo", help="Submit the demonstration analysis")
    demo.add_argument("--slug", default="southeast-michigan-demo")
    demo.add_argument("--start", default="2024-04-01")
    demo.add_argument("--end", default="2024-10-31")
    demo.add_argument("--cloud", type=float, default=30.0)
    demo.add_argument("--scenes", type=int, default=6)
    demo.add_argument(
        "--if-missing",
        action="store_true",
        help="Do nothing if a current-generation demo analysis already exists "
        "(idempotent; safe to run on every deployment)",
    )

    rq = sub.add_parser("requeue", help="Requeue a failed/stuck analysis")
    rq.add_argument("--analysis-id", required=True)

    dele = sub.add_parser(
        "delete-analysis",
        help="Permanently delete analyses and their stored artifacts",
    )
    dele.add_argument(
        "--analysis-id",
        action="append",
        help="Analysis to delete; repeat for several",
    )
    dele.add_argument(
        "--legacy",
        action="store_true",
        help="Delete every analysis processed before the canonical grid (grid IS NULL)",
    )
    dele.add_argument(
        "--dry-run", action="store_true", help="List what would be deleted, change nothing"
    )
    dele.add_argument(
        "--force",
        action="store_true",
        help="Allow deleting the analysis the landing page currently links to",
    )

    sub.add_parser("queue-depth", help="Print approximate queue depth")

    exp = sub.add_parser("export-demo", help="Export a demo bundle")
    exp.add_argument("--analysis-id", required=True)
    exp.add_argument("--out", default="data/demo/southeast-michigan")

    imp = sub.add_parser("import-demo", help="Import a demo bundle")
    imp.add_argument("--bundle", default="data/demo/southeast-michigan")

    args = parser.parse_args()
    try:
        asyncio.run(_run(args))
    except KeyboardInterrupt:
        sys.exit(130)


if __name__ == "__main__":
    main()

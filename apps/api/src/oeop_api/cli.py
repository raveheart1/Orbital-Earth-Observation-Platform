#: Artifact types small enough (and licensed appropriately) to ship in a
#: portable demo bundle. COGs are regenerated by running a real analysis.
#: Processing generation in which the canonical analysis grid was introduced.
#: Anything older produced observations that are not comparable across dates.
GRID_MAJOR_VERSION = 2


def _major_version(version: str | None) -> int:
    """Major component of a processing version; unparseable values read as 0."""
    if not version:
        return 0
    try:
        return int(str(version).split(".", 1)[0])
    except ValueError:
        return 0



async def seed_regions(session: AsyncSession) -> int:
    count = 0
    for spec in load_predefined_regions():
        bbox = validate_bbox(spec["bbox"])
        polygon = bbox_polygon(bbox)
        area = geodesic_area_km2(polygon)
        existing = (
            await session.execute(select(Region).where(Region.slug == spec["slug"]))
        ).scalar_one_or_none()
        if existing is None:
            session.add(
                Region(
                    name=spec["name"],
                    slug=spec["slug"],
                    description=spec["description"],
                    geometry=from_shape(polygon, srid=4326),
                    bbox=list(bbox),
                    area_km2=area,
                    is_predefined=True,
                )
            )
        else:
            existing.name = spec["name"]
            existing.description = spec["description"]
            existing.bbox = list(bbox)
            existing.geometry = from_shape(polygon, srid=4326)
            existing.area_km2 = area
        count += 1
    await session.commit()
    logger.info("regions_seeded", count=count)
    return count


async def seed_demo(
    session: AsyncSession,
    queue: AnalysisQueue,
    settings: Settings,
    *,
    slug: str,
    start: date,
    end: date,
    cloud: float,
    scenes: int,
    if_missing: bool = False,
) -> uuid.UUID | None:
    """Submit the demonstration analysis.

    With ``if_missing`` the command is idempotent and safe to run on every
    deployment: it does nothing when a demo analysis already exists in a
    usable state, so the landing page always has something to link to without
    paying for a reprocess on each deploy.
    """
    if if_missing:
        existing = (
            await session.execute(
                select(Analysis)
                .where(
                    Analysis.is_demo.is_(True),
                    Analysis.status.in_(
                        [
                            AnalysisStatus.SUCCEEDED,
                            AnalysisStatus.QUEUED,
                            AnalysisStatus.RUNNING,
                        ]
                    ),
                    # Only a current-generation demo counts; a legacy one would
                    # showcase pre-canonical-grid results.
                    Analysis.grid.is_not(None),
                )
                .order_by(Analysis.submitted_at.desc())
                .limit(1)
            )
        ).scalar_one_or_none()
        if existing is not None:
            logger.info(
                "demo_analysis_present",
                analysis_id=str(existing.id),
                status=existing.status.value,
            )
            print(existing.id)
            return existing.id

    region = (await session.execute(select(Region).where(Region.slug == slug))).scalar_one_or_none()
    if region is None:
        raise SystemExit(f"Region '{slug}' not found; run seed-regions first")
    analysis = await create_analysis(
        session=session,
        queue=queue,
        settings=settings,
        request=AnalysisCreateRequest(
            region_id=region.id,
            start_date=start,
            end_date=end,
            max_cloud_cover_pct=cloud,
            scene_limit=scenes,
        ),
        is_demo=True,
    )
    logger.info("demo_analysis_submitted", analysis_id=str(analysis.id))
    print(analysis.id)
    return analysis.id


async def delete_analyses(
    session: AsyncSession,
    blob: BlobStore,
    *,
    analysis_ids: list[uuid.UUID] | None = None,
    legacy: bool = False,
    dry_run: bool = False,
    force: bool = False,
) -> int:
    """Permanently delete analyses and their stored artifacts.

    Blobs are deleted BEFORE the database rows. That ordering matters: if the
    run is interrupted, rows pointing at missing blobs are visible and
    recoverable, whereas deleting rows first would leave orphaned blobs that
    nothing references and nobody notices (they would keep costing money until
    the lifecycle policy expired them).

    ``legacy`` targets analyses from a processing generation older than the
    canonical grid (major version < 2); those cannot be compared across dates
    when the AOI crossed a Sentinel-2 tile boundary.

    The filter deliberately keys on ``processing_version``, NOT on
    ``grid IS NULL``: an analysis that is still queued has no grid yet either,
    and sweeping those up would delete work in flight.
    """
    if legacy:
        result = await session.execute(select(Analysis).order_by(Analysis.submitted_at))
        targets = [
            a for a in result.scalars() if _major_version(a.processing_version) < GRID_MAJOR_VERSION
        ]
    elif analysis_ids:
        targets = []
        for analysis_id in analysis_ids:
            analysis = await session.get(Analysis, analysis_id)
            if analysis is None:
                raise SystemExit(f"Analysis {analysis_id} not found")
            targets.append(analysis)
    else:
        raise SystemExit("Provide --analysis-id or --legacy")

    if not targets:
        print("No matching analyses; nothing to delete.")
        return 0

    # Never remove work that is still in flight; a queued or running analysis
    # is not a stale record, and deleting it would strand a queue message.
    in_flight = [a for a in targets if a.status in (AnalysisStatus.QUEUED, AnalysisStatus.RUNNING)]
    if in_flight and not force:
        raise SystemExit(
            f"Refusing to delete {len(in_flight)} analyses that are still "
            f"{'/'.join(sorted({a.status.value for a in in_flight}))}. "
            "Wait for them to finish, or re-run with --force."
        )

    # Refuse to remove the analysis the landing page currently advertises,
    # unless explicitly forced — deleting it would leave a dead demo link.
    demo_id = await get_demo_analysis_id(session)
    protected = [a for a in targets if a.id == demo_id]
    if protected and not force:
        raise SystemExit(
            f"Refusing to delete {protected[0].id}: it is the demonstration "
            "analysis the public landing page links to. Re-run with --force if "
            "you really mean it, after seeding a replacement."
        )

    total_blobs = 0
    for analysis in targets:
        prefix = analysis.output_prefix or f"analyses/{analysis.id}"
        artifacts = (
            (await session.execute(select(Artifact).where(Artifact.analysis_id == analysis.id)))
            .scalars()
            .all()
        )
        size_mb = sum(a.size_bytes for a in artifacts) / 1e6
        label = (
            f"{analysis.id}  v{analysis.processing_version}  "
            f"{analysis.status.value}  {len(artifacts)} artifacts  {size_mb:.1f} MB"
        )
        if dry_run:
            print(f"  [dry-run] would delete {label}")
            continue

        deleted = blob.delete_prefix(prefix.rstrip("/") + "/")
        total_blobs += deleted
        await session.delete(analysis)  # cascades to scenes/observations/artifacts
        await session.commit()
        logger.info(
            "analysis_deleted",
            analysis_id=str(analysis.id),
            processing_version=analysis.processing_version,
            blobs_deleted=deleted,
        )
        print(f"  deleted {label}  ({deleted} blobs removed)")

    if dry_run:
        print(f"dry run: {len(targets)} analyses would be deleted (nothing changed)")
        return 0
    print(f"deleted {len(targets)} analyses and {total_blobs} blobs")
    return len(targets)


async def requeue(session: AsyncSession, queue: AnalysisQueue, analysis_id: uuid.UUID) -> None:
    analysis = await session.get(Analysis, analysis_id)
    if analysis is None:
        raise SystemExit(f"Analysis {analysis_id} not found")
    stale_cutoff = datetime.now(UTC) - timedelta(hours=2)
    if analysis.status == AnalysisStatus.RUNNING and (
        analysis.started_at is None or analysis.started_at > stale_cutoff
    ):
        raise SystemExit(
            "Analysis appears to be actively running; refusing to requeue. "
            "Wait for it to finish or become stale (>2h)."
        )
    if analysis.status == AnalysisStatus.SUCCEEDED:
        raise SystemExit("Analysis already succeeded; nothing to requeue.")
    analysis.status = AnalysisStatus.QUEUED
    analysis.status_message = "Requeued by operator"
    analysis.failure_category = None
    analysis.failure_detail = None
    analysis.retry_count += 1
    await session.commit()
    await anyio.to_thread.run_sync(queue.send_analysis, str(analysis_id))
    logger.info("analysis_requeued", analysis_id=str(analysis_id))
    print(f"requeued {analysis_id}")


def _record(obj: Any, fields: list[str]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for field in fields:
        value = getattr(obj, field)
        if isinstance(value, uuid.UUID):
            value = str(value)
        elif isinstance(value, datetime | date):
            value = value.isoformat()
        elif hasattr(value, "value") and not isinstance(value, int | float | str):
            value = value.value
        out[field] = value
    return out


